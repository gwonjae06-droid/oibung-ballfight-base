'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const {pathToFileURL}=require('node:url'),path=require('node:path');
const load=async p=>import(pathToFileURL(path.join(__dirname,'..',p)).href);
test('PvP profile validates skills and neutralizes client-reported damage, HP, and cooldowns',async()=>{
  const m=await load('workers/pvp-rules.mjs');
  const p=m.normalizeProfile({id:'cheater',name:'<img src=x>',color:'javascript:red',
    hp:999999,skills:[{name:'최강',type:'shot',damage:100000,cooldown:0},
      {name:'불법',type:'__eval',damage:9999},...Array(12).fill({type:'shot'})]});
  assert.equal(p.skills.length,4);
  assert.equal(p.skills[0].damage,m.ABILITIES.shot.damage);
  assert.equal(p.skills[0].cooldown,m.ABILITIES.shot.cooldown);
  assert.equal(p.skills[1].type,'shot');
  assert.equal(p.color,'#4f86c6');
  assert.equal(p.name.includes('<'),false);
  const room=m.createRoom(p,p,'manual',10000);
  assert.equal(room.players[0].hp,240);
  assert.equal(room.players[1].hp,240);
  const builtin=m.normalizeProfile({id:'park',name:'박성원'});
  assert.equal(builtin.skills.length,4);
  assert.equal(builtin.skills[1].type,'uppercut');
});
test('PvP manual mode requires player skill input and keeps distinct cooldowns',async()=>{
  const m=await load('workers/pvp-rules.mjs');
  const profile=m.normalizeProfile({skills:[{type:'shot'},{type:'wave'},{type:'shield'},{type:'heal'}]});
  const room=m.createRoom(profile,profile,'manual',1000);
  m.step(room,.05,1200);
  assert.equal(room.players[1].hp,240,'no manual skill fires by itself');
  assert.equal(m.setInput(room,0,{x:800,y:800},1200),true);
  assert.ok(Math.hypot(room.players[0].dx,room.players[0].dy)<=1.00001);
  m.step(room,.05,1200);
  assert.ok(room.players[0].x>110);
  assert.equal(m.cast(room,0,1,1201),false,'wave is outside of range');
  assert.equal(m.cast(room,0,1,1202),false,'cooldown now applies even on miss');
  assert.equal(m.cast(room,0,0,1202),true);
  assert.equal(m.cast(room,0,0,1203),false,'no immediate skill replay');
  assert.equal(room.players[0].ready[1],1201+m.ABILITIES.wave.cooldown*1000);
  assert.equal(m.cast(room,0,2,1203),true,'shield has independent clock');
  const hpBefore=room.players[1].hp;
  for(let i=0;i<38;i++)m.step(room,.05,1204+i*50);
  assert.ok(room.players[1].hp<hpBefore,'server-validated projectile collision deals damage');
  m.setInput(room,0,{x:1,y:0},7000);
  m.step(room,.05,7550);
  assert.equal(room.players[0].dx,0,'stale or disconnected input is cleared');
});
test('PvP automatic mode has server-run skills and a definitive victory or draw',async()=>{
  const m=await load('workers/pvp-rules.mjs');
  const p=m.normalizeProfile({skills:[{type:'shot'},{type:'shot'},{type:'wave'},{type:'heal'}]});
  const room=m.createRoom(p,p,'auto',1000);
  for(let t=1050;t<33000&&!room.ended;t+=50)m.step(room,.05,t);
  assert.ok(room.players.some(x=>x.ready.some(cd=>cd>0)),'server AI cast actual skills');
  const state=m.snapshot(room,33000);
  assert.equal(state.type,'state');assert.equal(state.players.length,2);
  assert.ok(state.players.every(x=>x.hp>=0&&x.hp<=240));
  const timed=m.createRoom(p,p,'manual',1000);
  m.step(timed,.05,121000);
  assert.equal(timed.ended,true);
  assert.equal(timed.winner,-1,'draw if timeout HP identical');
});
test('MatchHub keeps independent queues and sends results to two real socket peers',async()=>{
  const {MatchHub}=await load('workers/pvp-worker.mjs');
  const hub=new MatchHub({acceptWebSocket(){}},{});
  const make=()=>({sent:[],send(s){this.sent.push(JSON.parse(s));},close(){}});
  const a=make(),b=make(),c=make();
  for(const s of [a,b,c])hub.clients.set(s,{mode:null,room:null,slot:-1,lastPacket:0,packets:0});
  const join=(s,mode)=>hub.webSocketMessage(s,JSON.stringify({type:'queue',mode,profile:{name:'유저',skills:[{type:'wave'}]}}));
  join(a,'auto');join(b,'manual');
  assert.equal(hub.rooms.size,0);
  assert.equal(hub.waiting.auto.length,1);
  assert.equal(hub.waiting.manual.length,1);
  join(c,'manual');
  assert.equal(hub.rooms.size,1,'same mode connects two different users');
  assert.equal(hub.waiting.auto.length,1,'other mode remains in own queue');
  assert.ok(b.sent.some(v=>v.type==='matched'&&v.you===0));
  assert.ok(c.sent.some(v=>v.type==='matched'&&v.you===1));
  const room=[...hub.rooms.values()][0];
  assert.equal(room.mode,'manual');
  hub.webSocketMessage(b,JSON.stringify({type:'input',x:1,y:0}));
  hub.tick();
  assert.ok(room.players[0].x>=110);
  hub.webSocketMessage(c,JSON.stringify({type:'forfeit'}));
  assert.equal(hub.rooms.size,0);
  assert.ok(b.sent.some(v=>v.type==='result'&&v.winner===0));
  hub.webSocketClose(a);hub.webSocketClose(b);hub.webSocketClose(c);
  hub.tick();
  assert.equal(hub.interval,null);
});
test('MatchHub cancellation, drop and malicious messages never create fake matches',async()=>{
  const {MatchHub}=await load('workers/pvp-worker.mjs');
  const hub=new MatchHub({acceptWebSocket(){}},{});
  const make=()=>({sent:[],send(s){this.sent.push(JSON.parse(s));}});
  const a=make(),b=make();
  for(const s of [a,b])hub.clients.set(s,{mode:null,room:null,slot:-1,lastPacket:0,packets:0});
  hub.webSocketMessage(a,'not json');
  hub.webSocketMessage(a,JSON.stringify({type:'queue',mode:'manual',profile:{name:'A'}}));
  hub.webSocketMessage(a,JSON.stringify({type:'cancel'}));
  hub.webSocketMessage(b,JSON.stringify({type:'queue',mode:'manual',profile:{name:'B'}}));
  assert.equal(hub.rooms.size,0,'cancelled user cannot be matched');
  assert.equal(hub.waiting.manual.length,1);
  hub.webSocketClose(b);
  assert.equal(hub.waiting.manual.length,0,'closed socket cannot be matched');
  hub.webSocketMessage(a,JSON.stringify({type:'queue',mode:'superuser',profile:{}}));
  assert.ok(a.sent.some(x=>x.type==='error'));
});
